#!/usr/bin/env python3
"""
Write the pull-request body for a news update.

The PR body is what the review email actually contains, so it has to carry the
items themselves rather than a link to go and look at them. GitHub emails the
body to anyone subscribed to the repo -- including you, if "Your own updates"
is enabled in notification settings, which is what makes the daily run arrive
as a readable email with no mail server of our own.

Takes the news.json from before the merge and the one after, and lists what
was added. Same diff rule as announce-news.py so the review email and the
publish email cannot disagree about what is new.

Usage:
    news-pr-body.py <old-news.json> <new-news.json>
"""

import json
import sys
from pathlib import Path

NEWS_URL = "https://mountainfutures.ch/news"

GUIDANCE = """\
Every qualifying article is proposed as its own item, including several outlets
covering the same story — **the list is deliberately over-inclusive so you can
choose**. Delete the ones you don't want, keep the rest.

Merging publishes what's left and triggers a site deploy.

> [!IMPORTANT]
> **Check the links on `media` items.** Press items found by name search arrive
> with an opaque `news.google.com/rss/articles/...` redirect, because that is all
> Google News RSS returns — it can't be resolved automatically. Replace it with
> the real publisher URL before merging. Publication items from CrossRef/OpenAlex
> carry proper DOIs and are fine.
"""


def item_key(item):
    """Dedup key. Matches announce-news.py and merge-news.py."""
    return item.get("link") or item.get("slug") or f"{item.get('title', '')}|{item.get('date', '')}"


def load(path):
    try:
        return json.loads(Path(path).read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return []


def url(item):
    if item.get("slug"):
        return f"{NEWS_URL}/{item['slug']}"
    return item.get("link", "")


def main():
    if len(sys.argv) < 3:
        sys.stderr.write(__doc__)
        return 2

    old, new = load(sys.argv[1]), load(sys.argv[2])
    seen = {item_key(i) for i in old}
    added = [i for i in new if item_key(i) not in seen]

    n = len(added)
    out = [f"## {n} new item{'' if n == 1 else 's'} for the news feed", ""]

    for it in added:
        out.append(f"### {it['title']}")
        out.append("")
        out.append(f"**{it['date']}**")
        tags = it.get("tags") or []
        if tags:
            out.append(" · " + " ".join(f"`{t}`" for t in tags))
        out.append("")
        out.append(it.get("summary", "_no summary_"))
        link = url(it)
        if link:
            out.append("")
            out.append(f"[{link}]({link})")
        out.append("")

    out += ["---", "", GUIDANCE, "", "*Generated by `scripts/update-news.sh`*"]
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
