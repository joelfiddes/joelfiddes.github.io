#!/usr/bin/env bash
#
# Generates /etc/caddy/apps_auth.conf from /var/www/apps/apps.json.
# The Caddyfile imports apps_auth.conf inside the apps.mountainfutures.ch block.
# Re-run after editing apps.json, then: caddy validate && systemctl reload caddy
#
set -euo pipefail

APPS_JSON=/var/www/apps/apps.json
OUT=/etc/caddy/apps_auth.conf

# bcrypt hash of the shared app password (kept in a password manager).
# Regenerate with:  caddy hash-password --plaintext 'NEWPASSWORD'
HASH='REPLACE_WITH_BCRYPT_HASH'

# Space-separated path globs for every app with "protected": true.
# A leading "../" in a slug (e.g. the avaframe link) is stripped.
paths=$(jq -r '[.apps[] | select(.protected == true) | "/" + (.slug | ltrimstr("../")) + "*"] | join(" ")' "$APPS_JSON")

if [ -z "$paths" ]; then
    : > "$OUT"
    echo "No protected apps in $APPS_JSON; wrote empty $OUT"
else
    {
        echo "# AUTO-GENERATED by gen-apps-auth.sh from $APPS_JSON — do not edit by hand."
        echo "@protected path $paths"
        echo "basic_auth @protected {"
        echo "    mf $HASH"
        echo "}"
    } > "$OUT"
    echo "Wrote $OUT"
    echo "Protected paths: $paths"
fi
